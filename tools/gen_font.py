#!/usr/bin/env python3
# Generates app/src/font_data.h: ASCII 32..126, 8-bit alpha, DejaVu Sans Mono (Bitstream Vera licence).
import sys
from PIL import Image, ImageDraw, ImageFont
CW, CH, SIZE = 10, 20, 17
font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", SIZE)
out = ["/* Generated by tools/gen_font.py - DejaVu Sans Mono glyphs (Bitstream Vera / DejaVu licence). */",
       "#pragma once", f"#define FONT_W {CW}", f"#define FONT_H {CH}",
       "static const unsigned char font_alpha[95][FONT_W * FONT_H] = {"]
for code in range(32, 127):
    im = Image.new("L", (CW, CH), 0)
    ImageDraw.Draw(im).text((0, 0), chr(code), font=font, fill=255)
    out.append("{" + ",".join(str(v) for v in im.tobytes()) + "},")
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
